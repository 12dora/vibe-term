#!/usr/bin/env node
/**
 * i18n Build Script
 *
 * This script runs at build time to:
 * 1. Read all locale JSON files from src/i18n/locales/
 * 2. Merge them into a single resources.ts file
 * 3. Generate type definitions
 * 4. Emit the per-locale core/rest split consumed by the frontend
 * 5. Emit the locale metadata module and the gateway-only (server) bundles
 * 6. Keep the manifest.json for runtime use
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { type TranslationTree, splitTranslation } from '../src/i18n/core-keys';
import { pickServerTranslation } from '../src/i18n/server-keys';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const LOCALES_DIR = path.join(__dirname, '../src/i18n/locales');
const OUTPUT_FILE = path.join(__dirname, '../src/i18n/resources.ts');
const SPLIT_DIR = path.join(LOCALES_DIR, 'generated');

interface LocaleInfo {
  code: string;
  name: string;
  nativeName: string;
  flag: string;
  isDefault: boolean;
}

interface Manifest {
  locales: LocaleInfo[];
  defaultLocale: string;
}

function main() {
  console.log('[i18n] Building resources...');

  // Read manifest
  const manifestPath = path.join(LOCALES_DIR, 'manifest.json');
  const manifest: Manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));

  // Read all locale files
  const resources: Record<string, unknown> = {};

  for (const locale of manifest.locales) {
    const filePath = path.join(LOCALES_DIR, `${locale.code}.json`);

    if (!fs.existsSync(filePath)) {
      console.warn(`[i18n] Warning: Locale file not found: ${locale.code}.json`);
      continue;
    }

    const content = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
    resources[locale.code] = content;
    console.log(`[i18n] Loaded: ${locale.code} (${locale.nativeName})`);
  }

  // Generate TypeScript content
  const tsContent = generateTypeScript(resources);

  // Write output
  fs.writeFileSync(OUTPUT_FILE, tsContent, 'utf-8');
  console.log(`[i18n] Generated: ${path.relative(process.cwd(), OUTPUT_FILE)}`);

  // Generate types
  const typesContent = generateTypes(resources, manifest);
  const typesFile = path.join(__dirname, '../src/i18n/types.ts');
  fs.writeFileSync(typesFile, typesContent, 'utf-8');
  console.log(`[i18n] Generated: ${path.relative(process.cwd(), typesFile)}`);

  writeSplitBundles(resources);
  writeMetaModule(resources, manifest);
  writeServerBundles(resources, manifest);

  console.log(`[i18n] Build complete. ${Object.keys(resources).length} locales.`);
}

// 首屏语言包按 core/rest 切分：core 覆盖入口 chunk 用得到的 key，rest 由懒路由按需补齐。
function writeSplitBundles(resources: Record<string, unknown>): void {
  fs.mkdirSync(SPLIT_DIR, { recursive: true });

  for (const [code, content] of Object.entries(resources)) {
    const translation = translationOf(content);
    const { core, rest } = splitTranslation(translation);

    const leafCount = (tree: TranslationTree): number =>
      Object.values(tree).reduce<number>(
        (sum, value) => sum + (typeof value === 'string' ? 1 : leafCount(value)),
        0
      );
    const total = leafCount(translation);
    if (leafCount(core) + leafCount(rest) !== total) {
      throw new Error(`[i18n] core/rest split lost keys for ${code}`);
    }

    for (const [part, tree] of [
      ['core', core],
      ['rest', rest],
    ] as const) {
      const file = path.join(SPLIT_DIR, `${code}.${part}.json`);
      fs.writeFileSync(file, `${JSON.stringify({ translation: tree }, null, 2)}\n`, 'utf-8');
    }
    console.log(`[i18n] Split ${code}: core ${leafCount(core)} / rest ${leafCount(rest)} keys`);
  }
}

const GENERATED_HEADER = `// Auto-generated by scripts/build-i18n.ts
// Do not edit this file directly. Edit JSON files in locales/ instead.
`;

function translationOf(content: unknown): TranslationTree {
  return (content as { translation?: TranslationTree }).translation ?? {};
}

function writeGenerated(file: string, content: string): void {
  fs.writeFileSync(file, content, 'utf-8');
  console.log(`[i18n] Generated: ${path.relative(process.cwd(), file)}`);
}

// 语言元数据单独成模块：网关等只要 DEFAULT_LOCALE / toBCP47 的消费者不必加载整份 resources.ts。
function writeMetaModule(resources: Record<string, unknown>, manifest: Manifest): void {
  const codes = Object.keys(resources);
  const union = codes.map((code) => `'${code}'`).join(' | ');
  writeGenerated(
    path.join(SPLIT_DIR, 'meta.ts'),
    `${GENERATED_HEADER}
import type { Manifest } from '../../types';

export type LocaleCode = ${union};

export const DEFAULT_LOCALE: LocaleCode = '${manifest.defaultLocale}';

export const I18N_MANIFEST: Manifest = ${JSON.stringify(manifest, null, 2)} as const;

export function toBCP47(locale: LocaleCode): string {
  return locale.replace('_', '-');
}

export const AVAILABLE_LOCALES: LocaleCode[] = ${JSON.stringify(codes)};
`
  );
}

// 网关只持有服务端渲染用到的 key（前缀表见 src/i18n/server-keys.ts）：
// 默认语言静态 import 作兜底，其余语言各自一个模块，由网关首次用到时动态 import。
function writeServerBundles(resources: Record<string, unknown>, manifest: Manifest): void {
  const fallback = manifest.defaultLocale;
  for (const [code, content] of Object.entries(resources)) {
    const tree = pickServerTranslation(translationOf(content));
    writeGenerated(
      path.join(SPLIT_DIR, `${code}.server.ts`),
      `${GENERATED_HEADER}
import type { TranslationTree } from '../../core-keys';

const translation: TranslationTree = ${JSON.stringify(tree)};

export default translation;
`
    );
  }

  const loaders = Object.keys(resources)
    .filter((code) => code !== fallback)
    .map((code) => `  ${code}: () => import('./${code}.server'),`)
    .join('\n');
  writeGenerated(
    path.join(SPLIT_DIR, 'server.ts'),
    `${GENERATED_HEADER}
import type { TranslationTree } from '../../core-keys';
import fallback from './${fallback}.server';
import type { LocaleCode } from './meta';

export type { TranslationTree };

export type ServerTranslationModule = { default: TranslationTree };

export const SERVER_I18N_FALLBACK_LOCALE: LocaleCode = '${fallback}';

export const SERVER_I18N_FALLBACK: TranslationTree = fallback;

export const SERVER_I18N_LOADERS: Partial<
  Record<LocaleCode, () => Promise<ServerTranslationModule>>
> = {
${loaders}
};
`
  );
}

function generateTypeScript(resources: Record<string, unknown>): string {
  const resourceEntries = Object.entries(resources)
    .map(([code, content]) => {
      return `  ${code}: ${JSON.stringify(content, null, 2)} as const`;
    })
    .join(',\n');

  return `${GENERATED_HEADER}
export {
  AVAILABLE_LOCALES,
  DEFAULT_LOCALE,
  I18N_MANIFEST,
  type LocaleCode,
  toBCP47,
} from './locales/generated/meta';

export const I18N_RESOURCES = {
${resourceEntries}
} as const;

export type I18nResources = typeof I18N_RESOURCES;
`;
}

function generateTypes(resources: Record<string, unknown>, manifest: Manifest): string {
  // Extract nested keys from the first locale for type definitions
  const firstLocale = Object.values(resources)[0] as Record<string, unknown>;

  function extractKeys(obj: unknown, prefix = ''): string[] {
    if (typeof obj !== 'object' || obj === null) return [];

    const keys: string[] = [];
    for (const [key, value] of Object.entries(obj)) {
      const fullKey = prefix ? `${prefix}.${key}` : key;
      keys.push(fullKey);

      if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
        keys.push(...extractKeys(value, fullKey));
      }
    }
    return keys;
  }

  const translationKeys = extractKeys(firstLocale?.translation);

  return `// Auto-generated by scripts/build-i18n.ts
// Do not edit this file directly.

export interface LocaleInfo {
  code: string;
  name: string;
  nativeName: string;
  flag: string;
  isDefault: boolean;
}

export interface Manifest {
  locales: LocaleInfo[];
  defaultLocale: string;
}

export type TranslationKey =
${translationKeys.map((k) => `  | '${k}'`).join('\n')};
`;
}

main();
