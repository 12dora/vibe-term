/**
 * 设置类查询的缓存窗口。
 *
 * 模型、通知渠道、Webhook、快捷键、设备清单这些只在用户自己保存时才变，而 QueryClient 的
 * 全局默认 staleTime 只有 5 秒——切走再切回来必然重发一轮，隧道场景下就是几百毫秒的空转。
 * 30 秒既够覆盖一次来回切标签，又不至于让别处保存后的改动长时间看不到（保存路径都会
 * invalidate 对应的键，不依赖过期）。
 *
 * 实时状态（隧道 / 本机运行态 / TLS）不用这个值：它们各自带轮询，要的就是新鲜。
 */
export const SETTINGS_STALE_MS = 30_000;
