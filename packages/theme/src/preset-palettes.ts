// 每套包含两部分：ui（应用语义 token 的取色）与 terminal（终端 16 色 ANSI + fg/bg/cursor/selection）。
// themes.css 与 hljs-terminal-theme.css 的 [data-theme-preset="…"] 区块由
// scripts/theme/build-theme-presets.ts 从此文件生成，改完请重新生成并跑测试。

import type { TerminalThemeColors } from '@tmex/shared';
import type { ThemePreset } from './presets';

export type ThemeAppearance = 'light' | 'dark';

export interface PresetUiPalette {
  /** --background */
  background: string;
  /** --chat-surface：聊天区底色，比 background 再退一档 */
  chatSurface: string;
  /** --card / --popover */
  surface: string;
  /** --muted */
  muted: string;
  /** --accent / --sidebar-accent */
  accent: string;
  /** --sidebar */
  sidebar: string;
  /** --border / --sidebar-border */
  border: string;
  /** --input：比 border 再明显一档，保证输入框边缘可见 */
  input: string;
  /** --foreground 系列 */
  foreground: string;
  /** --muted-foreground：需对 background 达到 AA(4.5:1) */
  subtle: string;
  primary: string;
  primaryForeground: string;
  secondary: string;
  secondaryForeground: string;
  destructive: string;
  charts: readonly [string, string, string, string, string];
}

export interface PresetPalette {
  /** 品牌名，不参与 i18n */
  label: string;
  appearance: ThemeAppearance;
  ui: PresetUiPalette;
  terminal: TerminalThemeColors;
}

